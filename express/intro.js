/* What is express.js

    Express.js is lightweight, minimal & flexible framework for Node.js.
    Which is built on node.js's core http module.

    It is mainly used to build web server and REST API's.

    It provides features like routing, middleware, handling http request & response and error handling.
    which makes backend development with node.js easier and more structured.

*/


/* minimal and flexible

    Minimal means Express gives you only the basic building blocks (routing + middleware + req, res handling) 

    Flexible means it doesn't force you to follow fixed or strict architecture.
    We can structure your project in any ways
        - MVC (Model-View-Controller)
        - Microservice
*/

