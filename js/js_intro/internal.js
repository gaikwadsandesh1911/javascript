/*  Process and Thread

        Process:
            is running instance of your program. 
            When you run program Operating system create process.
                - Allocates memory on RAM
                - Load program code on RAM.                  
                    eg. when you open chrome. It becomes process.
        
        Thread  
            is smallest unit of execution withing process.
                - Every process has atleast 1 main thread 
                - Can also have multiple worker threads and background threads.
                - Threads share memory.
        
        CPU(processor)
                - processor gets instruction from RAM
                - processor has cores where threads get executed
                - OS decides which thread runs where
                - one cpu core execute one thread at a time.

                    
    Learn Time-Slicing and Context-Switching Operating System Concept.

*/
