/* Redux Thunk

    Redux Thunk is middleware that allows us to dispatch functions instead of only plain action objects.
    It is used to handle asynchronous logic, such as API requests.

    Normally, a Redux action is a plain object.
    But sometimes we need to perform an API request before updating the state.
    Thunk allows us to write a function that performs the API request

*/

/*  createAsyncThunk()

      It's a Redux Toolkit function used to handle asynchronous operations, such as API calls. 
      
      It automatically generates three action states: pending, fulfilled, and rejected.
    
      ----------
          createAsyncThunk() uses the thunk middleware internally. 
          Redux Toolkit includes that middleware by default.
     

*/

// userSlice.js

import { createSlice, createAsyncThunk } from "@reduxjs/toolkit";

export const fetchUsers = createAsyncThunk("users/fetchUsers", async () => {
    const response = await fetch(
      "https://jsonplaceholder.typicode.com/users"
    );

    if (!response.ok) {
      throw new Error("Failed to fetch users");
    }

    return await response.json();
  }
);


const userSlice = createSlice({
    
  name: "users",

  initialState: {
    users: [],
    loading: false,
    error: null
  },

  reducers: {},

  extraReducers: (builder) => {
    builder
      .addCase(fetchUsers.pending, (state) => {
        state.loading = true;
        state.error = null;
      })

      .addCase(fetchUsers.fulfilled, (state, action) => {
        state.loading = false;
        state.users = action.payload;
      })

      .addCase(fetchUsers.rejected, (state, action) => {
        state.loading = false;
        state.error = action.error.message;
      });
  }
});

export default userSlice.reducer;

/* extraReducers handle an actions generated outside the slice's own reducers.
   It is commonly used to handle the pending, fulfilled, and rejected actions generated by createAsyncThunk().

*/


// use in component
import { useEffect } from "react";
import { useSelector, useDispatch } from "react-redux";
import { fetchUsers } from "./userSlice";

function Users() {
    
  const dispatch = useDispatch();

  const { users, loading, error } = useSelector((state) => state.users);

// when component render we dispatch an action, extra reducer update the state, useSelector read it.
  useEffect(() => {
    dispatch(fetchUsers());
  }, [dispatch]);

  if (loading) return <p>Loading...</p>;

  if (error) return <p>{error}</p>;

  return (
    <div>
      {users.map((user) => (
        <p key={user.id}>{user.name}</p>
      ))}
    </div>
  );
}

export default Users;