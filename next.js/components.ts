/* Hydration

    "Hydration is the process where React attaches event handlers to server-rendered HTML in the browser and 
    makes the page interactive. 
    
    It happens after the browser receives the initial HTML and loads the required JavaScript."


  Hydration error

    since client componet is also pre-rendered on server and send generated html to client,
    A hydration error occurs when the HTML generated by the server does not match 
    the HTML that React generates during the initial browser render.

    React expects both outputs to match. If they differ, React reports a hydration mismatch.


  common causes of hydration errors are:

    - Using window, localStorage or document during rendering
    - Using Date.now() or Math.random() during rendering.
    - Different date or time formatting between server and browser.


  How to fix it?
  
    For browser-specific logic, use useEffect.

*/

