/* Partial Pre-rendering ( PPR )

  PPR is a Next.js feature that combines:

      Partial Prerendering combines Static Rendering and Dynamic Rendering on the same page.

    Instead of rendering the entire page at build time or request time, Next.js:
    - Pre-renders the static parts at build time.
    - Renders dynamic parts at request time.
    - Streams dynamic content when it becomes ready.
*/
